import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { selectOption, snapshot } from './browser-fixture.mjs';

export async function verifyCad(page) {
  const viewport = page.locator('.cad-viewport');
  await page.waitForFunction(() => window.canvasGallery?.cad?.snapshot().timings.length > 0);
  let data = await snapshot(page, 'cad');
  assert.equal(data.info.layers, 6); assert.ok(data.info.selected_outline_edges > 0);
  assert.equal(data.runtime.compilations, 1); assert.equal(data.runtime.activeInstances, 1);
  assert.ok(data.timings[0].elapsedMs < 3000, `单根首显 ${data.timings[0].elapsedMs} ms`);
  await page.getByRole('button', { name: '精细替换', exact: true }).click();
  await expect(viewport).toHaveAttribute('data-cad-model-kind', 'precise');
  await expect(viewport).toHaveAttribute('aria-busy', 'false');
  await selectOption(page, '选中对象', 'insulation');
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info.selected === 2);
  assert.ok((await snapshot(page, 'cad')).info.selected_outline_edges > 0);
  await page.getByRole('button', { name: '端面', exact: true }).click();
  await expect(viewport).toHaveAttribute('data-cad-view', 'end');
  await expect(page.locator('[data-cad-layer-dimensions]')).toBeVisible();
  await page.getByRole('button', { name: '剖面', exact: true }).click();
  await expect(viewport).toHaveAttribute('data-cad-mode', 'section');
  await selectOption(page, '选择方式', '原始直径');
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info.selection_kind === 'diameter');
  data = await snapshot(page, 'cad');
  assert.equal(data.info.original_topology_layers, 6);
  const oldHash = data.info.input_sha256;
  await page.evaluate(() => { window.canvasGallery.cad.replace('unkeyed-preview'); window.canvasGallery.cad.mismatchExact(true); });
  await expect(viewport).toHaveAttribute('aria-busy', 'false');
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info.selection_kind === 'part');
  await selectOption(page, '选择方式', '原始直径');
  await expect(viewport).toHaveAttribute('data-cad-state', 'error');
  await expect(viewport).toContainText('展示长度或层尺寸');
  data = await snapshot(page, 'cad');
  assert.equal(data.info.input_sha256, oldHash); assert.equal(data.info.original_topology_layers, 0);
  await page.evaluate(() => window.canvasGallery.cad.mismatchExact(false));
  await selectOption(page, '选择方式', '原始直径');
  await expect(viewport).toHaveAttribute('data-cad-state', 'success');
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info.original_topology_layers === 6);
  await page.evaluate(() => window.canvasGallery.cad.replace('invalid'));
  await expect(viewport).toHaveAttribute('data-cad-state', 'error');
  assert.equal((await snapshot(page, 'cad')).info.input_sha256, oldHash);
  await page.evaluate(() => window.canvasGallery.cad.replace('changed'));
  await expect(viewport).toHaveAttribute('data-cad-state', 'success');
  await expect(viewport).toHaveAttribute('aria-busy', 'false');
  data = await snapshot(page, 'cad');
  assert.notEqual(data.info.input_sha256, oldHash);
  assert.equal(data.info.selection_kind, 'part');
  assert.ok(data.timings.at(-1).elapsedMs < 3000);
  await page.getByRole('button', { name: '敷设场景', exact: true }).click();
  await expect(viewport).toHaveAttribute('aria-busy', 'false');
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info.scene);
  data = await snapshot(page, 'cad');
  assert.ok(data.info.scene_objects >= 8);
  assert.ok(data.info.selected_outline_edges > 0);
  const selectedGroup = data.info.selected_group;
  assert.ok(data.info.scene_opacities.filter(item => item.group === selectedGroup).every(item => item.display > .99));
  assert.ok(data.info.scene_opacities.filter(item => item.group !== selectedGroup).every(item => item.display <= .46));
  assert.ok(data.timings.at(-1).elapsedMs < 3000, `场景首显 ${data.timings.at(-1).elapsedMs} ms`);
  await page.evaluate(() => window.canvasGallery.cad.mount(false));
  await expect(viewport).toHaveCount(0);
  data = await snapshot(page, 'cad'); assert.equal(data.runtime.activeInstances, 0);
  assert.equal(data.runtime.createdInstances, data.runtime.disposedInstances);
  await page.context().setOffline(true);
  await page.evaluate(() => window.canvasGallery.cad.mount(true));
  await page.waitForFunction(() => window.canvasGallery.cad.snapshot().info?.scene);
  await page.context().setOffline(false);
  data = await snapshot(page, 'cad'); assert.equal(data.runtime.compilations, 1);
  assert.equal(data.runtime.activeInstances, 1); assert.equal(data.timings.at(-1).runtimeCacheHit, true);
  for (const state of ['empty', 'loading', 'error', 'historical', 'success']) {
    await page.evaluate(value => window.canvasGallery.setState(value), state);
    await expect(viewport).toHaveAttribute('data-cad-state', state);
    if (state === 'historical') await expect(viewport.locator('.stale-banner')).toBeVisible();
  }
  return { timings: data.timings, runtime: data.runtime };
}
