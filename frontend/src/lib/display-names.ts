export function displayName(key: string, fallback?: string): string {
  if (!key) return "—";
  if (displayNames[key]) return displayNames[key];
  if (["m", "ohm/m", "K*m/W", "1"].includes(key))
    return key === "1" ? "无量纲" : displayUnit(key);
  if (
    fallback &&
    /[\u3400-\u9fff]/.test(fallback) &&
    !/[a-z][a-z0-9]*_[a-z]/i.test(fallback)
  )
    return fallback;
  const entity =
    /^(circuit|core|cable|section|material|load|case|condition|layer)\/(?:[a-z]*)(\d+)(?:\/([ABC]))?$/.exec(
      key,
    );
  if (entity)
    return (
      prefixes[entity[1]] +
      " " +
      Number(entity[2]) +
      (entity[3] ? " · " + entity[3] + " 相" : "")
    );
  const sample = /^case-(\d+)$/.exec(key);
  if (sample) return "工况 " + (Number(sample[1]) + 1);
  const enclosure = /^enclosure\/(?:three-core-|duct-|e)?(\d+)$/.exec(key);
  if (enclosure) return "排管 " + Number(enclosure[1]);
  const cable = /^cable\/c(\d+)-([A-Za-z0-9]+)$/.exec(key);
  if (cable) return "电缆 " + cable[1] + "-" + cable[2];
  // Unknown names remain explicit so the global UI assertion catches missing vocabulary.
  return fallback ? `未翻译名称（${key}）` : key;
}
/** For server-authored messages. Replace complete registered tokens, never substring-edit user names. */
export function displayText(value: string): string {
  if (/Traceback \(most recent call last\):/.test(value))
    return "计算组件启动失败。请检查运行环境与依赖后重试；已保存的输入和结果仍保留。";
  return value.replace(/\bt_n\b/g, '标称厚度').replace(
    /[A-Za-z][A-Za-z0-9]*(?:[._/-][A-Za-z0-9]+)+|\b(?:ampacity|rating|operating|succeeded|failed|queued|running|available|unavailable|steady|transient|crosscheck)\b/g,
    (key) => displayName(key),
  );
}
export function displayUnit(unit: string): string {
  return unit
    .replaceAll("*", "·")
    .replaceAll("ohm", "Ω")
    .replaceAll("uF", "μF");
}
