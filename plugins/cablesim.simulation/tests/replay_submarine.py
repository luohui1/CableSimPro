AIR=[-.00227583562,1.15480022e-4,-7.90252856e-8,4.11702505e-11,-7.43864331e-15]
WATER=[-.869083936,.00894880345,-1.58366345e-5,7.97543259e-9]


def coupled_input(mesh):
    source='COMSOL6.2 tutorial06 final Multi coils, Rac(T) mean terminal constraint; native definition independently inspected, not native heat/mesh'
    provenance={'reference':mesh['geometry_source']+'; Gmsh '+mesh['mesher']['version'],'sha256':mesh['sha256']}
    discrete={k:mesh[k] for k in ('points','triangles','domain_ids')};discrete.update(length_unit='m',source=provenance)
    constants={3:1.,4:.46,5:.25,6:.46,7:10.,8:.17,9:1.38,10:17.5,11:.075281*400,12:35.3,13:58.}
    sigma={1:0.,3:1.,4:1e-18,5:1e-18,6:1e-18,7:2.,8:3.2e-9,9:1e-14,10:1.46e6,11:0.,12:4.55e6,13:4.03e6}
    thermal={};magnetic={};excitation=[];coils=[]
    for r in mesh['regions']:
        d=r['id'];mat=r['material_index'];label=r['construction_label']
        coef=AIR if mat==1 else WATER if mat==2 else [constants[mat]]
        lo,hi=(200.,1600.) if mat==1 else (273.15,553.75) if mat==2 else (273.15,393.15)
        thermal[str(d)]={'coefficients_w_m_k':coef,'minimum_temperature_k':lo,'maximum_temperature_k':hi,'source':source+'; material '+str(mat)}
        if label in ('gravel/exterior','water'):continue
        magnetic[str(d)]={'conductivity_s_m':sigma[mat],'relative_permeability':100. if mat==13 else 1.,'relative_permeability_loss':50. if mat==13 else 0.,
                         'alpha_per_k':.00386 if mat==12 else .0053 if mat==13 else 0.,'reference_temperature_k':293.15,
                         'minimum_temperature_k':273.15,'maximum_temperature_k':393.15,'source':source+'; material '+str(mat)}
        if mat==11:
            phase=int(label.split('/')[1]);angle={1:0.,2:-2*pi/3,3:2*pi/3}[phase];coils.append(d)
            excitation.append({'regions':['domain/'+str(d)],'kind':'impressed_current_rms_a','value':[655*cos(angle),655*sin(angle)],'source':source+'; phase '+str(phase)})
        elif sigma[mat]>0:
            excitation.append({'regions':['domain/'+str(d)],'kind':'voltage_gradient_v_m','value':[0.,0.],'source':source+'; Ampere law, zero axial potential gradient'})
    return {'schema_version':'cablesim.contact-electrothermal-field/1','mesh':discrete,'thermal_conductivity':thermal,
            'heat_w_m3':[0.]*len(mesh['triangles']),'heat_source':{'reference':'No imported electromagnetic heat; all heat is generated by the coupled solve','sha256':sha256(b'no-external-heat').hexdigest()},
            'contact_edges':mesh['contact_edges'],'contact_conductance_w_m2k':[float(np.polynomial.polynomial.polyval(293.15,AIR)/20e-6)]*len(mesh['contact_edges']),
            'contact_source':'COMSOL06 Thermal Contact selection,20um air layer; material input293.15K',
            'temperature_nodes':sorted({n for a,b,_,_ in mesh['boundary_edges'] for n in (a,b)}),'ambient_k':293.15,
            'boundary_source':'Tutorial06 fixed20C on exterior of [-5,5]x[-4,4]m domain; seabed interface z=1m',
            'frequency_hz':50.,'magnetic_domain_ids':[int(d) for d in magnetic],'magnetic_materials':magnetic,'excitations':excitation,
            'magnetic_boundary_source':'Tutorial06 A=0 at radius5*Dcab/2; independent Gmsh subset',
            'port_resistance':{'domain_ids':coils,'resistance_reference_ohm_m':1.39/(500e-6*59.6e6),'alpha_per_k':.0039,
                               'reference_temperature_k':293.15,'minimum_temperature_k':273.15,'maximum_temperature_k':393.15,
                               'source':'Tutorial06 analytic function Rac=1.39*Rcon*(1+ALcup*(T-Tmref)); ge1 equates it to mean real port resistance, including passive losses',
                               'scope':'mean_terminal_resistance_including_passive_losses'},
            'temperature_tolerance_k':1e-4,'power_relative_tolerance':1e-6,'maximum_iterations':40,'relaxation':.8}


def main():
    import argparse
    parser=argparse.ArgumentParser();parser.add_argument('--sizes',nargs='+',type=float,default=[.003,.002,.0013]);parser.add_argument('--segments',type=int,default=96);parser.add_argument('--resume',action='store_true');args=parser.parse_args()
    out=ROOT/'.data/simulation/submarine-coupled';out.mkdir(parents=True,exist_ok=True);jobs=ROOT/'.tmp/simulation-seventh-coupled';jobs.mkdir(parents=True,exist_ok=True)
    for size in args.sizes:
        key=f'{size:g}-{args.segments}';mesh_path=out/('mesh-'+key+'.json')
        if args.resume and mesh_path.exists():mesh=json.loads(mesh_path.read_text('utf-8'))
        else:
            mesh=build(size,args.segments);mesh_path.write_text(json.dumps(mesh,separators=(',',':'),allow_nan=False),'utf-8')
        value=coupled_input(mesh);request={'case_id':'submarine','input':value,'parameters':{}};input_path=out/('open-'+key+'-input.json');run_path=out/('open-'+key+'.json')
        if args.resume and run_path.exists() and input_path.exists() and json.loads(input_path.read_text('utf-8'))==request:
            run=json.loads(run_path.read_text('utf-8'))
        else:
            input_path.write_text(json.dumps(request,separators=(',',':'),allow_nan=False),'utf-8')
            print(json.dumps({'start':key,'nodes':len(mesh['points']),'domains':mesh['material_domain_counts']}),flush=True)
            run=asdict(Executor(jobs_root=jobs).run('cablesim.simulation','contact-electrothermal-field',[request]))
            run_path.write_text(json.dumps(run,ensure_ascii=False,separators=(',',':'),allow_nan=False),'utf-8')
        case=run['cases'][0]
        if case['status']!='succeeded':raise RuntimeError(case['error'])
        result=case['artifacts']['x-cablesim.simulation-bundle']['result']
        metadata={r['id']:r for r in mesh['regions']};groups={}
        for material,label in [(11,'conductor'),(12,'screen'),(13,'armor'),(10,'fiber')]:
            rows=[r for r in result['regional'] if metadata[r['domain_id']]['material_index']==material]
            areas=[metadata[r['domain_id']]['area_m2'] for r in rows]
            groups[label]={'heat_w_m':sum(r['heat_w_m'] for r in rows),'mean_temperature_k':sum(a*r['mean_temperature_k'] for a,r in zip(areas,rows))/sum(areas)}
        summary={'size_m':size,'circle_segments':args.segments,'nodes':len(mesh['points']),'maximum_k':result['maximum_temperature_k'],
                 'total_heat_w_m':result['total_heat_w_m'],'groups':groups,'iterations':result['iterations'],
                 'numerical_evidence':{k:result['thermal'][k] for k in ('relative_energy_error','maximum_contact_jump_k','linear_residual')},
                 'run':{k:run[k] for k in ('run_id','plugin_id','plugin_version','method_version','request_sha256')},
                 'artifact_sha256':case['artifact_digests']['x-cablesim.simulation-bundle'],'mesh_sha256':mesh['sha256'],
                 'input_file_sha256':sha256(input_path.read_bytes()).hexdigest(),'engineering_approval':False}
        (out/('summary-'+key+'.json')).write_text(json.dumps(summary,indent=2,allow_nan=False),'utf-8')
        print(json.dumps({k:summary[k] for k in ('size_m','nodes','maximum_k','total_heat_w_m','groups')}),flush=True)


if __name__=='__main__':main()
